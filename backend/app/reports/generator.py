"""
Autopsy Report Generator
Formats complete investigation findings into clear Markdown and JSON reports,
distinguishing observed facts, detected invariants, hypotheses, and replay findings.
"""

from typing import Dict, Any, Optional
from backend.app.schemas.run import AgentRun
from backend.app.schemas.diagnosis import AutopsyDiagnosis
from backend.app.schemas.experiment import ReplayExperiment
from backend.app.schemas.evaluation import RegressionEvaluationReport


class ReportGenerator:
    """
    Generates structured Autopsy reports for developers and stakeholders.
    """
    @staticmethod
    def generate_markdown_report(
        run: AgentRun,
        diagnosis: AutopsyDiagnosis,
        experiment: Optional[ReplayExperiment] = None,
        evaluation: Optional[RegressionEvaluationReport] = None
    ) -> str:
        """
        Creates an executive markdown autopsy report.
        """
        top_candidate = diagnosis.candidates[0] if diagnosis.candidates else None

        report = f"""# Agent Autopsy Investigation Report

**Run ID:** `{run.run_id}`  
**Agent:** `{run.agent_name}`  
**Initial Verdict:** **{diagnosis.verdict}**  
**Scenario:** `{run.scenario_id or 'Custom Query'}`  

---

## 1. Executive Summary
{diagnosis.summary}

---

## 2. Observed Execution Facts
- **Input Goal:** {run.input_summary}
- **Total Trace Events:** {run.total_events}
- **Visible Failure Symptoms:**
"""
        if diagnosis.failure_symptoms:
            for s in diagnosis.failure_symptoms:
                report += f"  - ⚠️ {s}\n"
        else:
            report += "  - None. Run completed without detected failure symptoms.\n"

        report += """
---

## 3. Root Cause Hypothesis & Evidence
"""
        if top_candidate:
            report += f"""- **Candidate Mistake Event:** `{top_candidate.candidate_step_id}`
- **Category:** `{top_candidate.category}`
- **Diagnosis Confidence:** `{top_candidate.confidence.upper()}`
- **Causal Hypothesis:** {top_candidate.causal_hypothesis}
- **Supporting Trace Evidence IDs:** {', '.join([f'`{eid}`' for eid in top_candidate.evidence_event_ids])}
"""
        else:
            report += "No decisive candidate step was isolated.\n"

        if experiment:
            report += f"""
---

## 4. Replay Lab: Counterfactual Verification
- **Experiment ID:** `{experiment.experiment_id}`
- **Intervention Type:** `{experiment.intervention.type}` on `{experiment.intervention.target_event_id}`
- **Baseline Result:** `{experiment.baseline_verdict}` ➔ **Replay Result:** `{experiment.replay_verdict}`
- **Downstream Steps Changed:** {experiment.changed_events_count}
- **Hypothesis Proven in Sandbox:** {'✅ YES - Failure resolved safely' if experiment.hypothesis_supported else '❌ NO - Failure persisted'}
"""

        if evaluation:
            report += f"""
---

## 5. Regression Suite Evaluation (10 Benchmark Cases)
- **Fix Tested:** {evaluation.fix_description}
- **Rescue Rate:** **{evaluation.rescue_rate}%** ({evaluation.rescued_count}/5 failing cases fixed)
- **Break Rate:** **{evaluation.break_rate}%** ({evaluation.broken_count}/5 passing controls broken)
- **Deployment Verdict:** **{evaluation.verdict}**
"""

        report += """
---
*Generated by Agent Autopsy Investigation Engine*
"""
        return report
